import type { SessionUser } from '@itsm/contracts';
export let currentUser: SessionUser | null = null;
export function setUser(user: SessionUser | null) { currentUser = user; }
export function devUser() { return sessionStorage.getItem('itsm-dev-user') ?? 'employee-1'; }
let development = false;
export function useDevelopment(value: boolean) { development = value; }
export class ApiError extends Error {
  constructor(public status: number,public code: string,public appointmentId?:string) { super(code); }
}
export async function api<T>(path: string,options: { method?: string; body?: unknown; key?: string; signal?:AbortSignal } = {}): Promise<T> {
  const response = await fetch(`/api/v1${path}`,{
    method:options.method ?? 'GET',credentials:'same-origin',headers:{
      ...(development ? { 'X-Dev-User':devUser() } : {}),
      ...(options.body !== undefined ? { 'Content-Type':'application/json' } : {}),
      ...(options.key ? { 'Idempotency-Key':options.key } : {}),
      ...(currentUser?.csrfToken ? { 'X-CSRF-Token':currentUser.csrfToken } : {}),
      ...(path === '/auth/dingtalk' ? { 'X-ITSM-Login':'1' } : {}),
    },body:options.body === undefined ? undefined : JSON.stringify(options.body),signal:options.signal,
  });
  const data = await response.json().catch(() => ({}));
  if (!response.ok) throw new ApiError(response.status,data.code ?? 'REQUEST_FAILED',
    typeof data.appointmentId==='string'?data.appointmentId:undefined);
  return data as T;
}
export async function attachmentRequest(url:string,method:'GET'|'PUT',headers:Record<string,string>,body?:Blob):Promise<Response> {
  if(!/^\/api\/v1\/tickets\/[a-f0-9-]{36}\/attachments\/[a-f0-9-]{36}\/content$/i.test(url))throw new ApiError(400,'INVALID_ATTACHMENT');
  const response=await fetch(url,{method,credentials:'same-origin',redirect:'error',headers:{...headers,
    ...(development?{'X-Dev-User':devUser()}:{}),...(currentUser?.csrfToken?{'X-CSRF-Token':currentUser.csrfToken}:{})},body,signal:AbortSignal.timeout(150_000)});
  if(!response.ok){const data=await response.json().catch(()=>({}));throw new ApiError(response.status,data.code??'REQUEST_FAILED');}
  return response;
}
