import {test,expect} from './fixtures';
import {recordedOperation} from './operation-log-helpers';

test('administrator directly configures scoped member privileges and revokes them with centralized history',async({page})=>{
  test.setTimeout(120000);
  const reason=`成员授权验收 ${Date.now()}`;
  await page.setViewportSize({width:1440,height:1000});await page.goto('/');
  await expect(page.getByRole('button',{name:'支持组',exact:true})).toHaveCount(0);
  await page.getByRole('combobox',{name:'开发身份'}).selectOption('demo-admin-1');
  const open=async()=>{
    await page.getByRole('button',{name:'支持组',exact:true}).click();
    await page.getByRole('tab',{name:'支持组与成员',exact:true}).click();
    await page.getByRole('combobox',{name:'当前支持组'}).selectOption('service-desk');
    await page.getByRole('button',{name:'配置服务台工程师权限',exact:true}).click();
    const modal=page.getByRole('dialog',{name:'成员权限'});
    await expect(modal.getByRole('checkbox',{name:'P1 复核',exact:true})).toBeVisible();return modal;
  };
  const dialog=await open();
  const names=['P1 复核','知识编辑','知识审校'];
  const initial=await Promise.all(names.map(name=>dialog.getByRole('checkbox',{name,exact:true}).isChecked()));
  const initialService=await dialog.getByRole('checkbox',{name:/REQ-ACCOUNT/}).isChecked();
  await expect(dialog.getByRole('button',{name:'保存并生效'})).toBeDisabled();
  for(const name of ['P1 复核','知识编辑','知识审校'])await dialog.getByRole('checkbox',{name,exact:true}).check();
  const service=dialog.getByRole('checkbox',{name:/REQ-ACCOUNT/});await service.check();
  await dialog.getByRole('textbox',{name:'变更依据',exact:true}).fill(reason);
  await dialog.getByRole('checkbox',{name:'本次内容不含密码、密钥及安全事件证据'}).check();
  await expect(dialog.getByRole('button',{name:'保存并生效'})).toBeEnabled();
  await page.screenshot({path:'test-results/member-privileges-desktop.png',fullPage:true});
  await dialog.getByRole('button',{name:'保存并生效'}).click();await expect(dialog).toHaveCount(0);
  const member=page.getByRole('region',{name:'组内成员'}).getByRole('listitem',{name:'服务台工程师',exact:true});
  await expect(member).toContainText('P1 复核');await expect(member).toContainText('知识审校');
  const row=await recordedOperation(page,'roles',reason,'service-desk');
  await row.getByRole('button',{name:/^查看日志 /}).click();
  const audit=page.getByRole('dialog',{name:'操作日志详情'});
  await expect(audit).toContainText('member_privilege_audits');await expect(audit).toContainText('REQ-ACCOUNT');
  await audit.getByRole('button',{name:'关闭日志详情'}).click();
  await open();
  for(const name of ['P1 复核','知识编辑','知识审校'])await expect(dialog.getByRole('checkbox',{name,exact:true})).toBeChecked();
  await expect(service).toBeChecked();
  await page.setViewportSize({width:390,height:844});
  await dialog.getByRole('textbox',{name:'搜索可授权服务'}).fill('不存在的服务');
  await expect(dialog.getByText('没有匹配的服务')).toBeVisible();
  await dialog.getByRole('textbox',{name:'搜索可授权服务'}).fill('');
  await page.screenshot({path:'test-results/member-privileges-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await dialog.focus();await page.keyboard.press('Shift+Tab');
  expect(await dialog.evaluate(el=>el.contains(document.activeElement))).toBe(true);
  for(const [index,name] of names.entries())await dialog.getByRole('checkbox',{name,exact:true}).setChecked(initial[index]);
  await service.setChecked(initialService);await dialog.getByRole('textbox',{name:'变更依据',exact:true}).fill(`${reason} 撤销`);
  await dialog.getByRole('checkbox',{name:'本次内容不含密码、密钥及安全事件证据'}).check();
  await dialog.getByRole('button',{name:'保存并生效'}).click();await expect(dialog).toHaveCount(0);
  if(!initial.some(Boolean)&&!initialService)await expect(member).not.toContainText('P1 复核');
  await recordedOperation(page,'roles',`${reason} 撤销`,'service-desk');
  await open();
  for(const [index,name] of names.entries())await expect(dialog.getByRole('checkbox',{name,exact:true})).toBeChecked({checked:initial[index]});
  await expect(service).toBeChecked({checked:initialService});
  await dialog.getByRole('button',{name:'关闭成员权限'}).click();
  await page.getByRole('combobox',{name:'开发身份'}).selectOption('agent-1');
  await expect(page.getByRole('button',{name:'配置服务台工程师权限',exact:true})).toHaveCount(0);
});
