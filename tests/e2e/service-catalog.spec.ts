import { test,expect } from './fixtures';

test('administrators configure a new service domain through actual employee intake without changing code',async({page})=>{
  test.setTimeout(120000);
  const suffix=String(Date.now()),domain=`自定义设备服务域 ${suffix}`,system=`试验设备平台 ${suffix}`,position=`设备平台工程师 ${suffix}`;
  const name=`试验设备故障 ${suffix}`,code=`INC-E2E-${suffix}`;
  await page.setViewportSize({width:1440,height:1000});await page.goto('/');
  await page.getByRole('combobox',{name:'开发身份'}).selectOption('demo-admin-1');
  await page.getByRole('button',{name:'服务组织',exact:true}).click();
  await page.getByRole('button',{name:'新增责任域',exact:true}).click();
  let form=page.getByRole('region',{name:'编辑责任域'});
  await form.getByRole('textbox',{name:'名称',exact:true}).fill(domain);
  await form.getByRole('button',{name:'确认修改',exact:true}).click();
  await page.getByRole('tab',{name:'业务系统',exact:true}).click();
  await page.getByRole('button',{name:'新增业务系统',exact:true}).click();
  form=page.getByRole('region',{name:'编辑业务系统'});
  await form.getByRole('textbox',{name:'名称',exact:true}).fill(system);
  await form.getByRole('combobox',{name:'责任域',exact:true}).selectOption({label:domain});
  await form.getByRole('button',{name:'确认修改',exact:true}).click();
  await page.getByRole('tab',{name:'岗位',exact:true}).click();
  await page.getByRole('button',{name:'新增岗位',exact:true}).click();
  form=page.getByRole('region',{name:'编辑岗位'});
  await form.getByRole('textbox',{name:'名称',exact:true}).fill(position);
  await form.getByRole('combobox',{name:'责任域',exact:true}).selectOption({label:domain});
  await form.getByRole('combobox',{name:'支持组',exact:true}).selectOption('service-desk');
  await form.getByRole('button',{name:'确认修改',exact:true}).click();
  await page.getByRole('tab',{name:'任职人员',exact:true}).click();
  await page.getByRole('button',{name:'新增任职人员',exact:true}).click();
  form=page.getByRole('region',{name:'编辑任职人员'});
  await form.getByRole('combobox',{name:'岗位',exact:true}).selectOption({label:`${position} · IT 服务台`});
  await form.getByRole('textbox',{name:'查找任职人员',exact:true}).fill('agent-1');
  await form.getByRole('button',{name:'搜索人员',exact:true}).click();
  await form.getByRole('combobox',{name:'任职人员',exact:true}).selectOption('agent-1');
  await form.getByRole('button',{name:'确认修改',exact:true}).click();

  await page.getByRole('tab',{name:'目录维护',exact:true}).click();
  await page.getByRole('button',{name:'新增服务项',exact:true}).click();
  form=page.getByRole('region',{name:'编辑服务项'});
  await form.getByRole('textbox',{name:'服务编码',exact:true}).fill(code);
  await form.getByRole('textbox',{name:'服务名称',exact:true}).fill(name);
  await form.getByRole('textbox',{name:'服务描述',exact:true}).fill('试验设备运行异常及恢复');
  await form.getByRole('combobox',{name:'默认支持组',exact:true}).selectOption('service-desk');
  await form.getByRole('combobox',{name:'责任域',exact:true}).selectOption({label:domain});
  await form.getByRole('combobox',{name:'关联业务系统',exact:true}).selectOption({label:system});
  await form.getByRole('combobox',{name:'主办岗位',exact:true}).selectOption({label:position});
  await form.getByRole('button',{name:'新增字段',exact:true}).click();
  await form.getByRole('textbox',{name:'字段编码',exact:true}).fill('device');
  await form.getByRole('textbox',{name:'字段名称',exact:true}).fill('设备编码');
  await form.getByRole('checkbox',{name:'必填',exact:true}).check();
  await page.screenshot({path:'test-results/service-catalog-editor-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'test-results/service-catalog-editor-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await form.getByRole('button',{name:'确认目录草稿',exact:true}).click();

  async function publish(reason:string){
    const publishing=page.getByRole('region',{name:'配置发布'});
    await publishing.getByRole('textbox',{name:'变更依据'}).fill(reason);
    await publishing.getByRole('checkbox',{name:'本次内容不含密码、密钥及安全事件证据'}).check();
    await publishing.getByRole('button',{name:'预览分派',exact:true}).click();
    await expect(publishing).toContainText('服务台工程师');
    await publishing.getByRole('button',{name:'保存并生效',exact:true}).click();
    await expect(page.getByRole('status')).toContainText('配置已保存并生效');
    await page.getByRole('tab',{name:'变更记录',exact:true}).click();
    await page.getByRole('row').filter({hasText:reason}).getByRole('button',{name:'查看完整配置',exact:true}).click();
    const reviewing=page.getByRole('region',{name:'配置复核'});
    await expect(reviewing.getByRole('region',{name:'服务目录变更明细'})).toContainText(code);
    await expect(reviewing).toContainText('设备编码');
    await page.screenshot({path:'test-results/service-catalog-review-mobile.png',fullPage:true});
    await expect(reviewing.getByRole('button',{name:'批准发布',exact:true})).toHaveCount(0);
  }
  await publish(`发布试验设备服务 ${suffix}`);
  await page.getByRole('combobox',{name:'开发身份'}).selectOption('employee-1');
  await page.getByRole('button',{name:'服务目录',exact:true}).click();
  await page.getByRole('button',{name:new RegExp(name)}).click();
  await page.getByRole('textbox',{name:'问题标题'}).fill(`试验设备不可用 ${suffix}`);
  await page.getByRole('textbox',{name:'详细情况'}).fill('设备无响应，请检查连接和运行状态');
  await page.getByRole('combobox',{name:'影响范围'}).selectOption('INDIVIDUAL');
  await page.getByRole('combobox',{name:'紧急程度'}).selectOption('LOW');
  await page.getByRole('textbox',{name:'设备编码',exact:true}).fill('LAB-01');
  await page.getByRole('checkbox',{name:'本次内容不含密码、密钥及安全事件证据'}).check();
  await page.getByRole('button',{name:'核对信息',exact:true}).click();
  await page.getByRole('button',{name:'确认提交',exact:true}).click();
  await expect(page.getByRole('heading',{name:`试验设备不可用 ${suffix}`,exact:true})).toBeVisible();
  await page.getByRole('combobox',{name:'开发身份'}).selectOption('demo-admin-1');
  await page.getByRole('button',{name:'服务组织',exact:true}).click();
  await page.getByRole('tab',{name:'目录维护',exact:true}).click();
  await page.getByRole('button',{name:`编辑目录${name}`,exact:true}).click();
  form=page.getByRole('region',{name:'编辑服务项'});
  await form.getByRole('checkbox',{name:'发布服务项',exact:true}).uncheck();
  await form.getByRole('button',{name:'确认目录草稿',exact:true}).click();
  await publish(`停用试验设备服务 ${suffix}`);
  await page.getByRole('combobox',{name:'开发身份'}).selectOption('employee-1');
  await page.getByRole('button',{name:'服务目录',exact:true}).click();
  await expect(page.getByRole('button',{name:new RegExp(name)})).toHaveCount(0);
});
