  await page.getByRole('combobox',{name:'开发身份'}).selectOption('agent-1');
  await page.getByRole('button',{name:'IT 工作台',exact:true}).click();
  await page.screenshot({path:'test-results/workbench-desktop.png',fullPage:true});
